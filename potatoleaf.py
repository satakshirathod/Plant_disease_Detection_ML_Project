from tensorflow.keras.applications.mobilenet_v2 import preprocess_input

# --- 1. SETUP DATA AUGMENTATION ---
# This creates "variations" of your images so the model isn't tricked by angles
data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal_and_vertical"),
    layers.RandomRotation(0.2),
    layers.RandomZoom(0.1),
])

# --- 2. SETUP BASE MODEL ---
base_model = tf.keras.applications.MobileNetV2(
    input_shape=(224, 224, 3),
    include_top=False,
    weights='imagenet'
)
base_model.trainable = False

# --- 3. ASSEMBLE THE COMPLETE MODEL ---
model = models.Sequential([
    layers.Input(shape=(224, 224, 3)),   # Define the input layer
    data_augmentation,                  # <--- FIX 1: Augmentation (Training only)
    layers.Lambda(preprocess_input),     # <--- FIX 2: Normalization (Crucial!)
    base_model,
    layers.GlobalAveragePooling2D(),
    layers.Dropout(0.3),                 # Slightly higher dropout for better generalization
    layers.Dense(len(class_names), activation='softmax')
])

model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])

# --- STEP 6: TRAINING ---
print("\nStarting Training (Phase 1: Head Only)...")
history = model.fit(train_ds, validation_data=val_ds, epochs=5)

# Fine-tuning to reach >90% accuracy
print("\nStarting Fine-tuning (Phase 2: All Layers)...")
base_model.trainable = True
model.compile(optimizer=optimizers.Adam(1e-5), loss='categorical_crossentropy', metrics=['accuracy'])
history_fine = model.fit(train_ds, validation_data=val_ds, epochs=5)

# --- STEP 7: EVALUATION & PLOTS ---
# Combine histories
acc = history.history['accuracy'] + history_fine.history['accuracy']
val_acc = history.history['val_accuracy'] + history_fine.history['val_accuracy']
loss = history.history['loss'] + history_fine.history['loss']
val_loss = history.history['val_loss'] + history_fine.history['val_loss']

plt.figure(figsize=(12, 5))
plt.subplot(1, 2, 1)
