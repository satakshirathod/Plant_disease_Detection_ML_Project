# --- STEP 3: PATH CONFIGURATION ---
# We check the directory to make sure we have the right path
base_dir = "/content/potato_data/PLD_3_Classes_256"
train_dir = os.path.join(base_dir, "Training")
val_dir = os.path.join(base_dir, "Validation")

# Load datasets
BATCH_SIZE = 32
IMAGE_SIZE = (224, 224)

train_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    image_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    label_mode='categorical'
)

val_ds = tf.keras.utils.image_dataset_from_directory(
    val_dir,
    image_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    label_mode='categorical'
)

class_names = train_ds.class_names
print(f"Detected classes: {class_names}")

# Count files per class
counts = [len(os.listdir(os.path.join(train_dir, name))) for name in class_names]

plt.figure(figsize=(15, 5))

