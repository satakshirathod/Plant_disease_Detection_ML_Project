print("\nGenerating Confusion Matrix...")
y_true, y_pred = [], []
for x, y in val_ds:
    y_true.extend(np.argmax(y.numpy(), axis=1))
    y_pred.extend(np.argmax(model.predict(x, verbose=0), axis=1))

